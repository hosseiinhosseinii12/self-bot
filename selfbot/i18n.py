def t(key: str, **kwargs) -> str:
    lang = CONFIG.get("language", "en")
    if lang not in STRINGS:
        lang = "en"
    text = STRINGS[lang].get(key) or STRINGS["en"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text